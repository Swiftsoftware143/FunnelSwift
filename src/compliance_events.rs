//! The provider's own verdict on every message we send (2026-11-22).
//!
//! WHY THIS EXISTS. `email_suppressions` has been the app's do-not-mail list since the compliance
//! work landed: the gate in `email::send_template_email_for_tenant` honours it, the public opt-out
//! page writes to it, and the operator's console can add and remove rows. What was missing was the
//! one source that can fill it WITHOUT a human noticing something went wrong: the provider's
//! delivery events. Measured on this account (2026-11-22), `GET /v3/domains/<domain>` answered
//! `"webhooks": {}` for all six app domains — so a hard bounce or a spam complaint was reported to
//! NOBODY, the address stayed unsuppressed, and the next campaign or notice mailed a dead mailbox
//! again. That is the fastest way to damage the sending domain, which is a shared asset: when it is
//! throttled, a customer's password-reset stops arriving and they cannot get into the product.
//!
//! TWO RULES, both taken from the sibling app's receiver (CoreSwift `mail_compliance/webhook`):
//!  1. The endpoint has no session, so the credential is IN THE PATH: a secret this app generates
//!     (48 hex chars) and stores in `admin_settings.mailgun_events_token`. It is compared in
//!     constant time; a wrong token is a 403 that writes nothing. A URL token is used INSTEAD of a
//!     signature because Mailgun's account-level webhook signing key is not the API credential this
//!     app holds (measured on this account 2026-11-19), so an HMAC check would refuse every real
//!     delivery. The URL travels over TLS to the provider and is useless on another host.
//!  2. An event is attributed to a workspace by the RECIPIENT ADDRESS, resolved against this app's
//!     own rows (`users` first, then `leads`), never by anything else in the body. An address no
//!     workspace owns is acknowledged and ignored — the provider is not told who our customers are.
//!
//! WHAT IT RECORDS, all through `compliance::suppress` so the row is identical to one the operator
//! or the opt-out page would write:
//!  * `failed` with severity `permanent`, or `rejected`  -> reason `hard_bounce`, class `all`
//!  * `complained`                                        -> reason `complaint`,  class `all`
//!  * `unsubscribed`                                      -> reason `unsubscribed`, class `all`
//!
//! A temporary failure suppresses NOTHING (a full mailbox is not a dead one), and `delivered` is
//! ignored here — delivery is already watched by the fleet's own daily probe.
//!
//! Both shapes are accepted: Mailgun's webhook POST (`{"event-data": {...}}`), the events-API item
//! (`{...}`) and a JSON array of items, so the same endpoint can be replayed from a shell.

use axum::{
    body::Bytes,
    extract::{Path, State},
    response::Json,
};
use serde_json::{json, Value};
use sqlx::PgPool;
use uuid::Uuid;

use crate::error::AppError;
use crate::state::AppState;

/// `admin_settings` key holding the secret carried in the webhook URL.
const TOKEN_KEY: &str = "mailgun_events_token";

fn constant_time_eq(a: &[u8], b: &[u8]) -> bool {
    if a.len() != b.len() {
        return false;
    }
    let mut diff = 0u8;
    for (x, y) in a.iter().zip(b.iter()) {
        diff |= x ^ y;
    }
    diff == 0
}

/// The webhook token, created on first use.
///
/// Created lazily rather than shipped in a migration so a fresh install has no shared secret in the
/// repository: the first caller (the operator reading the URL, or a real event) mints it, and
/// `ON CONFLICT DO NOTHING` makes two concurrent callers agree on one value.
pub async fn token(pool: &PgPool) -> Result<String, sqlx::Error> {
    if let Some(existing) =
        sqlx::query_scalar::<_, String>("SELECT value #>> '{}' FROM admin_settings WHERE key = $1")
            .bind(TOKEN_KEY)
            .fetch_optional(pool)
            .await?
    {
        if !existing.trim().is_empty() {
            return Ok(existing);
        }
    }
    let fresh = format!("{}{}", Uuid::new_v4().simple(), Uuid::new_v4().simple());
    sqlx::query(
        "INSERT INTO admin_settings (key, value, description, updated_at)
         VALUES ($1, to_jsonb($2::text), 'Secret carried in the mail-provider events webhook URL (generated by the app)', NOW())
         ON CONFLICT (key) DO NOTHING",
    )
    .bind(TOKEN_KEY)
    .bind(&fresh)
    .execute(pool)
    .await?;
    sqlx::query_scalar::<_, String>("SELECT value #>> '{}' FROM admin_settings WHERE key = $1")
        .bind(TOKEN_KEY)
        .fetch_one(pool)
        .await
}

/// POST /api/v1/webhooks/mailgun/events/:token — the provider's delivery events.
pub async fn events_webhook(
    State(state): State<AppState>,
    Path(supplied): Path<String>,
    body: Bytes,
) -> Result<Json<Value>, AppError> {
    let expected = token(&state.pool)
        .await
        .map_err(|e| AppError::Internal(format!("could not read the events token: {e}")))?;
    if !constant_time_eq(expected.as_bytes(), supplied.as_bytes()) {
        tracing::warn!("mail events refused — the URL token does not match");
        return Err(AppError::Forbidden("unknown mail-events endpoint".into()));
    }

    let parsed: Value = serde_json::from_slice(&body)
        .map_err(|e| AppError::BadRequest(format!("expected JSON: {e}")))?;

    // One POST may carry one event (the webhook shape, wrapped in `event-data`), a bare event (the
    // events-API shape) or a batch (an array) — the same code path for all three.
    let items: Vec<&Value> = match &parsed {
        Value::Array(list) => list.iter().collect(),
        Value::Object(map) => match map.get("event-data") {
            Some(inner) => vec![inner],
            None => vec![&parsed],
        },
        _ => return Err(AppError::BadRequest("expected an event object".into())),
    };

    let mut recorded = 0usize;
    let mut ignored = 0usize;
    for item in items {
        let event = item.get("event").and_then(Value::as_str).unwrap_or("");
        let severity = item.get("severity").and_then(Value::as_str).unwrap_or("");
        let reason = match (event, severity) {
            ("failed", "permanent") | ("rejected", _) => "hard_bounce",
            ("complained", _) => "complaint",
            ("unsubscribed", _) => "unsubscribed",
            _ => {
                ignored += 1;
                continue;
            }
        };
        let Some(address) = recipient(item) else {
            ignored += 1;
            continue;
        };
        let Some(tenant_id) = tenant_for(&state.pool, &address).await else {
            // A real bounce for an address no workspace owns is not ours to record; acknowledging it
            // keeps the provider from retrying a delivery we will never act on.
            tracing::info!(address = %address, event = %event, "mail event ignored — no workspace owns the address");
            ignored += 1;
            continue;
        };
        match crate::compliance::suppress(
            &state.pool,
            tenant_id,
            &address,
            "all",
            reason,
            "provider_event",
        )
        .await
        {
            Ok(()) => {
                recorded += 1;
                tracing::info!(
                    tenant = %tenant_id,
                    address = %address,
                    reason = %reason,
                    "mail event recorded — address suppressed"
                );
            }
            Err(e) => {
                tracing::error!(tenant = %tenant_id, address = %address, error = %e, "mail event could not be recorded");
                return Err(AppError::Internal(format!(
                    "could not record the event: {e}"
                )));
            }
        }
    }

    // The path just proved itself: the provider reached us with a real payload. Record WHEN, so the
    // console can tell the workspace owner the safety net is live instead of asking them to paste a
    // URL into a provider they do not control (`webhook_url` reads this back).
    record_receipt(&state.pool, recorded, ignored).await;

    Ok(Json(json!({ "recorded": recorded, "ignored": ignored })))
}

/// The last verified delivery report this installation received (`admin_settings.mail_events_last`).
///
/// Written for EVERY verified POST, including one that suppresses nothing: the fact worth showing is
/// that the provider's events reach this app at all. A write failure never fails the event.
async fn record_receipt(pool: &PgPool, recorded: usize, ignored: usize) {
    let payload = json!({
        "at": chrono::Utc::now().to_rfc3339(),
        "recorded": recorded,
        "ignored": ignored,
    });
    if let Err(e) = sqlx::query(
        "INSERT INTO admin_settings (key, value, description, updated_at)
         VALUES ('mail_events_last', $1, 'The last delivery report the mail provider posted to this installation (written by the events receiver)', NOW())
         ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value, updated_at = NOW()",
    )
    .bind(payload)
    .execute(pool)
    .await
    {
        tracing::warn!("could not record the last mail event: {e}");
    }
}

/// The address an event is about, in either provider shape.
fn recipient(item: &Value) -> Option<String> {
    let raw = item
        .get("recipient")
        .and_then(Value::as_str)
        .map(str::to_string)
        .or_else(|| {
            item.get("message")
                .and_then(|m| m.get("headers"))
                .and_then(|h| h.get("to"))
                .and_then(Value::as_str)
                .map(str::to_string)
        })?;
    // `"Name <a@b.c>"` and a bare address are both possible; the list stores the address.
    let trimmed = raw.trim();
    let address = match (trimmed.rfind('<'), trimmed.rfind('>')) {
        (Some(open), Some(close)) if close > open => &trimmed[open + 1..close],
        _ => trimmed,
    };
    let address = address.trim();
    if address.contains('@') {
        Some(crate::compliance::normalise(address))
    } else {
        None
    }
}

/// Which workspace owns this address. Users first (an owner or teammate), then leads.
async fn tenant_for(pool: &PgPool, address: &str) -> Option<Uuid> {
    if let Ok(Some(id)) = sqlx::query_scalar::<_, Uuid>(
        "SELECT tenant_id FROM users
          WHERE lower(email) = lower($1) AND tenant_id IS NOT NULL
          ORDER BY created_at LIMIT 1",
    )
    .bind(address)
    .fetch_optional(pool)
    .await
    {
        return Some(id);
    }
    sqlx::query_scalar::<_, Uuid>(
        "SELECT tenant_id FROM leads
          WHERE lower(email) = lower($1) AND tenant_id IS NOT NULL
          ORDER BY created_at DESC LIMIT 1",
    )
    .bind(address)
    .fetch_optional(pool)
    .await
    .ok()
    .flatten()
}

/// GET /api/v1/settings/do-not-mail/webhook — the URL the operator pastes into the provider.
pub async fn webhook_url(
    State(state): State<AppState>,
    auth: crate::auth::middleware::AuthUser,
) -> Result<Json<Value>, (axum::http::StatusCode, String)> {
    // WHO may read it: the workspace's OWNER, not a role string (measured 2026-11-23). This check
    // used to be `role == admin|company_admin`, but FunnelSwift's signup writes `role = "user"` for
    // the very person who created the workspace — so the only human in a self-serve account was
    // refused the one address he has to paste into the provider, and bounce/complaint suppression
    // could never be switched on by the customer it protects. `is_workspace_owner` is the same rule
    // the team doors and PATCH /api/v1/workspace use (creator, appointed company_admin, or the
    // platform operator), so the answer here now matches every other "you own this workspace" door.
    let tenant_uuid = Uuid::parse_str(&auth.tenant_id).map_err(|_| {
        (
            axum::http::StatusCode::BAD_REQUEST,
            "invalid tenant".to_string(),
        )
    })?;
    match crate::handlers::team_handler::is_workspace_owner(&state, &auth, tenant_uuid).await {
        Ok(true) => {}
        Ok(false) => {
            return Err((
                axum::http::StatusCode::FORBIDDEN,
                "only a workspace owner can read the mail-events URL".to_string(),
            ))
        }
        Err(e) => {
            tracing::warn!("could not check workspace ownership for the mail-events URL: {e}");
            return Err((
                axum::http::StatusCode::INTERNAL_SERVER_ERROR,
                "could not check who owns this workspace".to_string(),
            ));
        }
    }
    let token = token(&state.pool)
        .await
        .map_err(|e| (axum::http::StatusCode::INTERNAL_SERVER_ERROR, e.to_string()))?;
    let url = format!(
        "{}/api/v1/webhooks/mailgun/events/{}",
        crate::email::APP_URL.trim_end_matches('/'),
        token
    );
    // WHEN the provider last reported something. The console shows this instead of asking a customer
    // to paste the address into a provider they do not control — measured 2026-11-23: no domain on
    // this account had a webhook registered, so the safety net was inert while the screen implied the
    // customer could switch it on. A read failure answers `null`, which the screen words as "waiting
    // for the first report" rather than as an error.
    let last_event_at = sqlx::query_scalar::<_, Option<String>>(
        "SELECT value ->> 'at' FROM admin_settings WHERE key = 'mail_events_last'",
    )
    .fetch_optional(&state.pool)
    .await
    .ok()
    .flatten();
    Ok(Json(json!({
        "url": url,
        "events": ["permanent_fail", "complained", "unsubscribed"],
        "last_event_at": last_event_at,
    })))
}
